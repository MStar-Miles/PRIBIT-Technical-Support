CREATE OR REPLACE VIEW `VW_TREE_CLUD_USER_GRUP`
AS
    with recursive TR_CLUD_USER_GRUP
        as (select `G`.`SCUGRUP_ID` AS `RCUGRUP_ID`,
                    `G`.`SGRUP_NM` AS `RGRUP_NM`,
                    `G`.`SCUGRUP_ID` AS `CUGRUP_ID`,
                    `G`.`SREF_USER_GRUP_ID` AS `REF_USER_GRUP_ID`,
                    `G`.`SGRUP_NM` AS `GRUP_NM`,
                    `G`.`SCLUD_ID` AS `CLUD_ID`,
                    1 AS `LVL`
            from `TB_CLUD_USER_GRUP` `G`
            where `G`.`SCUGRUP_ID` <> `G`.`SREF_USER_GRUP_ID`
            union
            select `TG`.`RCUGRUP_ID` AS `RCUGRUP_ID`,
                    `TG`.`RGRUP_NM` AS `RGRUP_NM`,
                    `G`.`SCUGRUP_ID` AS `SCUGRUP_ID`,
                    `G`.`SREF_USER_GRUP_ID` AS `SREF_USER_GRUP_ID`,
                    `G`.`SGRUP_NM` AS `SGRUP_NM`,
                    `G`.`SCLUD_ID` AS `SCLUD_ID`,
                    `TG`.`LVL` + 1 AS `LVL+1`
            from (`TB_CLUD_USER_GRUP` `G` join `TR_CLUD_USER_GRUP` `TG`)
            where `TG`.`CUGRUP_ID` = `G`.`SREF_USER_GRUP_ID`
            and `TG`.`CLUD_ID` = `G`.`SCLUD_ID`
            and `G`.`SCUGRUP_ID` <> `G`.`SREF_USER_GRUP_ID`
            )
select `A`.`RCUGRUP_ID` AS `SRCUGRUP_ID`,
        `A`.`RGRUP_NM` AS `SRGRUP_NM`,
        `A`.`CUGRUP_ID` AS `SCUGRUP_ID`,
        `A`.`REF_USER_GRUP_ID` AS `SREF_USER_GRUP_ID`,
        `A`.`GRUP_NM` AS `SGRUP_NM`,
        `A`.`CLUD_ID` AS `SCLUD_ID`,
        `A`.`LVL` AS `LVL`
from `TR_CLUD_USER_GRUP` `A`;



